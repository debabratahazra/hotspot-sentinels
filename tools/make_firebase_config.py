"""Generate public/firebase-config.js from the Firebase Management API.

The Firebase web apiKey is public by design — it identifies the project and is
protected by Firestore security rules, not by secrecy. It is still generated at
deploy time rather than committed, so the repository keeps a clean no-keys rule
and the gitleaks check never has to be weakened to accommodate an exception.

    python tools/make_firebase_config.py
"""

import json
import os
import subprocess
import sys
import urllib.request
from pathlib import Path

PROJECT = os.getenv("GOOGLE_CLOUD_PROJECT", "hotspot-sentinels-7364")
OUTPUT = Path(__file__).resolve().parents[1] / "public" / "firebase-config.js"
REQUIRED = ("apiKey", "authDomain", "projectId", "appId")


def access_token() -> str:
    result = subprocess.run(
        ["gcloud", "auth", "print-access-token"],
        capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        sys.exit("Could not obtain an access token. Run: gcloud auth login")
    return result.stdout.strip()


def api(path: str, token: str) -> dict:
    request = urllib.request.Request(
        f"https://firebase.googleapis.com/v1beta1/{path}",
        headers={"Authorization": f"Bearer {token}", "x-goog-user-project": PROJECT},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def main() -> None:
    token = access_token()
    apps = api(f"projects/{PROJECT}/webApps", token).get("apps", [])
    if not apps:
        sys.exit(f"No Firebase web app in {PROJECT}. Create one first.")
    config = api(f"projects/{PROJECT}/webApps/{apps[0]['appId']}/config", token)

    missing = [key for key in REQUIRED if not config.get(key)]
    if missing:
        sys.exit(f"Firebase config is missing {missing}; refusing to write a broken file.")

    payload = {key: config[key] for key in REQUIRED if key in config}
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "// Generated by tools/make_firebase_config.py — do not commit.\n"
        "// The Firebase web apiKey is public by design; Firestore security rules,\n"
        "// not secrecy, are what protect the data.\n"
        f"export const firebaseConfig = {json.dumps(payload, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"  wrote {OUTPUT.relative_to(Path.cwd())} for project {config['projectId']}")


if __name__ == "__main__":
    main()
